func TestTitleIsTheFirstRealRequest(t *testing.T) {
	dir := t.TempDir()
	claudePath := filepath.Join(dir, "c.jsonl")
	var b strings.Builder
	b.WriteString(jsonLine(t, map[string]any{"type": "file-history-snapshot"}))
	b.WriteString(jsonLine(t, claudeMsg("user", "Caveat: The messages below were generated", map[string]any{"isMeta": true})))
	b.WriteString(jsonLine(t, claudeMsg("user", "修好\n登录页   的验证码", nil)))
	os.WriteFile(claudePath, []byte(b.String()), 0o600)
	if got := Title(claudePath); got != "修好 登录页 的验证码" {
		t.Fatalf("claude title %q", got)
	}

	codexPath := filepath.Join(dir, "x.jsonl")
	b.Reset()
	b.WriteString(jsonLine(t, map[string]any{"type": "session_meta", "payload": map[string]any{"id": "x"}}))
	b.WriteString(jsonLine(t, map[string]any{"type": "response_item", "payload": map[string]any{"type": "message", "role": "user", "content": []any{map[string]any{"type": "input_text", "text": "# AGENTS.md instructions\n\n<INSTRUCTIONS>x</INSTRUCTIONS>"}}}}))
	b.WriteString(jsonLine(t, map[string]any{"type": "response_item", "payload": map[string]any{"type": "message", "role": "user", "content": []any{map[string]any{"type": "input_text", "text": strings.Repeat("长", 80)}}}}))
	os.WriteFile(codexPath, []byte(b.String()), 0o600)
	if got := Title(codexPath); got != strings.Repeat("长", 60)+"…" {
		t.Fatalf("codex title %q", got)
	}

	empty := filepath.Join(dir, "e.jsonl")
	os.WriteFile(empty, []byte(jsonLine(t, map[string]any{"type": "file-history-snapshot"})), 0o600)
	if got := Title(empty); got != "" {
		t.Fatalf("a session nobody spoke in has no title, got %q", got)
	}
}

