func TestWriteClaudeKeepsTheEnding(t *testing.T) {
	t.Setenv("GCCCODE_HOME", t.TempDir())
	path := filepath.Join(t.TempDir(), "sess.jsonl")
	var b strings.Builder
	for i := 0; i < 30; i++ {
		b.WriteString(`{"type":"user","message":{"role":"user","content":[{"type":"text","text":"问题` + strings.Repeat("甲", 20) + `"}]}}` + "\n")
		b.WriteString(`{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"回答` + strings.Repeat("乙", 20) + `"}]}}` + "\n")
	}
	os.WriteFile(path, []byte(b.String()), 0o600)
	out, err := WriteClaude(path, "sess-1")
	if err != nil {
		t.Fatal(err)
	}
	text, _ := os.ReadFile(out)
	s := string(text)
	if !strings.Contains(s, "会话接力") || !strings.Contains(s, "问题") {
		t.Fatalf("handoff missing body: %s", s[:200])
	}
	if strings.Contains(s, "encrypted") {
		t.Fatal("encrypted content leaked")
	}
}

func jsonLine(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b) + "\n"
}

func claudeMsg(role string, content any, extra map[string]any) map[string]any {
	m := map[string]any{"type": role, "message": map[string]any{"role": role, "content": content}}
	for k, v := range extra {
		m[k] = v
	}
	return m
}

func toolUse(name string, input any) []any {
	return []any{map[string]any{"type": "tool_use", "id": "t", "name": name, "input": input}}
}

func sectionOf(t *testing.T, note, heading string) string {
	t.Helper()
	head := "## " + heading + "\n\n"
	i := strings.Index(note, head)
	if i < 0 {
		return ""
	}
	s := note[i+len(head):]
	if j := strings.Index(s, "\n## "); j >= 0 {
		s = s[:j]
	}
	return s
}

func TestClaudeNoteHasGoalTodosFilesAndDecisions(t *testing.T) {
	t.Setenv("GCCCODE_HOME", t.TempDir())
	cwd := t.TempDir()
	var b strings.Builder
	b.WriteString(jsonLine(t, claudeMsg("user", "Caveat: The messages below were generated by the user while running local commands.", map[string]any{"isMeta": true, "cwd": cwd})))
	b.WriteString(jsonLine(t, claudeMsg("user", "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>", map[string]any{"cwd": cwd})))
	b.WriteString(jsonLine(t, claudeMsg("user", "做一个记账小程序，要支持多人共享账本", map[string]any{"cwd": cwd})))
	b.WriteString(jsonLine(t, claudeMsg("assistant", toolUse("TodoWrite", map[string]any{"todos": []any{
		map[string]any{"content": "旧计划", "status": "pending"},
	}}), nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", toolUse("Write", map[string]any{"file_path": filepath.Join(cwd, "src", "app.ts"), "content": "x"}), nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", toolUse("Edit", map[string]any{"file_path": "/etc/elsewhere.conf"}), nil)))
	b.WriteString(jsonLine(t, claudeMsg("user", []any{map[string]any{"type": "tool_result", "tool_use_id": "t", "content": `User has answered your questions: "后端用什么？"="Supabase"`}}, nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", toolUse("TodoWrite", map[string]any{"todos": []any{
		map[string]any{"content": "建表", "status": "completed"},
		map[string]any{"content": "共享邀请", "status": "in_progress"},
		map[string]any{"content": "导出 CSV", "status": "pending"},
	}}), nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", []any{map[string]any{"type": "text", "text": "子代理的内部输出"}}, map[string]any{"isSidechain": true})))
	for i := 0; i < 40; i++ {
		b.WriteString(jsonLine(t, claudeMsg("user", "继续"+strings.Repeat("丙", 300), nil)))
		b.WriteString(jsonLine(t, claudeMsg("assistant", []any{map[string]any{"type": "text", "text": "好的" + strings.Repeat("丁", 300)}}, nil)))
	}
	b.WriteString(jsonLine(t, claudeMsg("user", "继续", nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", []any{map[string]any{"type": "text", "text": "You've hit your limit · resets 5pm"}}, map[string]any{"isApiErrorMessage": true})))
	path := filepath.Join(t.TempDir(), "s.jsonl")
	os.WriteFile(path, []byte(b.String()), 0o600)

	out, err := WriteClaude(path, "s1")
	if err != nil {
		t.Fatal(err)
	}
	raw, _ := os.ReadFile(out)
	note := string(raw)
	if got := sectionOf(t, note, goalHeading); !strings.Contains(got, "多人共享账本") {
		t.Fatalf("goal lost after many turns: %q", got)
	}
	todos := sectionOf(t, note, todoHeading)
	if !strings.Contains(todos, "[x] 建表") || !strings.Contains(todos, "共享邀请（进行中）") || strings.Contains(todos, "旧计划") {
		t.Fatalf("want the latest todo list, got %q", todos)
	}
	files := sectionOf(t, note, filesHeading)
	if !strings.Contains(files, "`"+filepath.Join("src", "app.ts")+"`") || !strings.Contains(files, "/etc/elsewhere.conf") {
		t.Fatalf("edited files: %q", files)
	}
	if !strings.Contains(note, "工作目录：`"+cwd+"`") {
		t.Fatal("working directory missing")
	}
	if !strings.Contains(note, "### 用户（上一个号还没回应这条）\n\n继续") {
		t.Fatal("the request the limit cut off must stand out")
	}
	for _, bad := range []string{"hit your limit", "子代理的内部输出", "Caveat:", "<command-name>"} {
		if strings.Contains(note, bad) {
			t.Fatalf("%q leaked into the note", bad)
		}
	}
	r, _ := claudeRecord(path)
	answered := false
	for _, tr := range r.turns {
		answered = answered || (tr.role == "user" && strings.Contains(tr.text, "Supabase"))
	}
	if !answered {
		t.Fatal("the user's answer to a question was dropped")
	}
}

