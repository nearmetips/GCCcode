func TestChainedHandoffKeepsTheOriginalGoal(t *testing.T) {
	t.Setenv("GCCCODE_HOME", t.TempDir())
	first := filepath.Join(t.TempDir(), "a.jsonl")
	os.WriteFile(first, []byte(jsonLine(t, claudeMsg("user", "把登录页改成手机号验证码登录\n\n## 细节\n要防刷", nil))), 0o600)
	note1, err := WriteClaude(first, "a")
	if err != nil {
		t.Fatal(err)
	}
	second := filepath.Join(t.TempDir(), "b.jsonl")
	var b strings.Builder
	b.WriteString(jsonLine(t, claudeMsg("user", Prompt+note1, nil)))
	b.WriteString(jsonLine(t, claudeMsg("assistant", []any{map[string]any{"type": "text", "text": "已接手"}}, nil)))
	os.WriteFile(second, []byte(b.String()), 0o600)
	note2, err := WriteClaude(second, "b")
	if err != nil {
		t.Fatal(err)
	}
	raw, _ := os.ReadFile(note2)
	goal := sectionOf(t, string(raw), goalHeading)
	if !strings.Contains(goal, "手机号验证码") || strings.Contains(goal, Prompt) {
		t.Fatalf("a second handoff must carry the first task, got %q", goal)
	}
	if !strings.Contains(string(raw), "要防刷") {
		t.Fatal("a heading inside the user's own goal cut it short")
	}
}

